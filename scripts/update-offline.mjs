import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const directories = ['src','ace','vendor','examples','gallery/previews','icons'];
let assets = ['index.html','gallery.html','icon.svg','manifest.webmanifest','svg-pan-zoom.min.js','service-worker.js','LICENSE-graphvizonline','LICENSE-svg-pan-zoom'];
async function walk(directory) {
  for (const entry of await fs.readdir(new URL(directory+'/', root), { withFileTypes: true })) {
    const path = directory + '/' + entry.name;
    if (entry.isDirectory()) await walk(path);
    else assets.push(path);
  }
}
for (const directory of directories) await walk(directory);
assets = assets.sort();
const hash = createHash('sha256');
for (const asset of assets) { hash.update(asset); hash.update(await fs.readFile(new URL(asset, root))); }
const manifest = { version: 'gnuplot-' + hash.digest('hex').slice(0,16), assets: [...assets,'offline-assets.js','https://cdnjs.cloudflare.com/ajax/libs/lz-string/1.5.0/lz-string.min.js'] };
const source = '/** Generated by node scripts/update-offline.mjs after changing shipped files. */\nconst OfflineAssets = '+JSON.stringify(manifest,null,2)+";\nif (typeof module !== 'undefined') module.exports = OfflineAssets;\nelse globalThis.OfflineAssets = OfflineAssets;\n";
if (process.argv.includes('--check')) {
  if (await fs.readFile(new URL('offline-assets.js', root),'utf8') !== source) throw new Error('Offline asset manifest is stale. Run node scripts/update-offline.mjs.');
} else await fs.writeFile(new URL('offline-assets.js', root), source);
console.log(manifest.version + ': ' + manifest.assets.length + ' files');
